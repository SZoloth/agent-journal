"""Add or remove the journal's hooks without replacing other client settings."""

import argparse
import json
import os
from pathlib import Path
import shlex
import stat
import sys
import tempfile

from adapter import CLIENTS, EVENTS, TOOL_EVENT


def update(path, client, remove):
    path = path.expanduser().resolve()
    original = path.read_bytes() if path.exists() else None
    settings = json.loads(original) if original is not None else {}
    changed = configure_desktop(settings, remove) if client == "claude-desktop" else configure_hooks(settings, client, remove)
    if not changed:
        return False
    save_settings(path, original, settings)
    return True


def configure_desktop(settings, remove):
    servers = settings.setdefault("mcpServers", {})
    desired = {"command": sys.executable, "args": [str(Path(__file__).with_name("journal_mcp.py").resolve())]}
    present = servers.get("agent-journal")
    if present is not None and present != desired:
        raise ValueError("agent-journal already has a different desktop configuration")
    if remove and present is not None:
        del servers["agent-journal"]
        return True
    if not remove and present is None:
        servers["agent-journal"] = desired
        return True
    return False


def configure_hooks(settings, client, remove):
    command = shlex.join([sys.executable, str(Path(__file__).with_name("adapter.py").resolve()), "hook", client])
    registry = settings.setdefault("hooks", {})
    changed = False
    events = ("SessionStart", "SessionEnd", "AfterAgent") if client == "gemini" else EVENTS
    for event in (*events, TOOL_EVENT[client]):
        tool = event == TOOL_EVENT[client]
        timeout = (12000 if tool else 3000) if client == "gemini" else (12 if tool else 3)
        hook = {"type": "command", "command": command, "timeout": timeout}
        group = {"hooks": [hook]}
        if tool:
            group["matcher"] = "run_shell_command" if client == "gemini" else "Bash"
        groups = registry.get(event, [])
        # Own only the exact standalone group generated by this installer.
        matching = [candidate for candidate in groups if candidate == group]
        if remove and matching:
            remaining = [group for group in groups if group not in matching]
            if remaining:
                registry[event] = remaining
            else:
                del registry[event]
            changed = True
        if not remove and not matching:
            registry[event] = [*groups, group]
            changed = True
    return changed


def save_settings(path, original, settings):
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = stat.S_IMODE(path.stat().st_mode) if original is not None else 0o600
    fd, name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.journal-")
    temporary = Path(name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            os.fchmod(output.fileno(), mode)
            json.dump(settings, output, ensure_ascii=False, indent=2)
            output.write("\n")
            output.flush()
            os.fsync(output.fileno())
        if (path.read_bytes() if path.exists() else None) != original:
            raise OSError("settings changed during installation; retry")
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("client", choices=(*CLIENTS, "claude-desktop"))
    parser.add_argument("--settings", type=Path)
    parser.add_argument("--remove", action="store_true")
    args = parser.parse_args()
    defaults = {
        "codex": Path(os.environ.get("CODEX_HOME", Path.home() / ".codex")) / "hooks.json",
        "claude": Path(os.environ.get("CLAUDE_CONFIG_DIR", Path.home() / ".claude")) / "settings.json",
        "gemini": Path(os.environ.get("GEMINI_CLI_HOME", Path.home())) / ".gemini" / "settings.json",
        "claude-desktop": Path.home() / "Library/Application Support/Claude/claude_desktop_config.json",
    }
    path = args.settings or defaults[args.client]
    try:
        changed = update(path, args.client, args.remove)
    except (OSError, ValueError, TypeError, AttributeError) as error:
        parser.exit(1, f"agent-journal: {error}\n")
    print(f"{path}: {'updated' if changed else 'already up to date'}")


if __name__ == "__main__":
    main()
